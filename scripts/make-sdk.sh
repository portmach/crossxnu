#!/usr/bin/env bash
# Create the synthetic "kernel SDK" that XNU's makefiles expect.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=env.sh
source "${SCRIPT_DIR}/env.sh"

SDK="${CROSSXNU_SDK}"
XNU="${CROSSXNU_XNU}"

if [[ ! -d "${XNU}" ]]; then
    echo "error: XNU sources not found at ${XNU}" >&2
    exit 1
fi

rm -rf "${SDK}"
mkdir -p \
    "${SDK}/usr/local/libexec" \
    "${SDK}/usr/include/mach-o" \
    "${SDK}/usr/local/include/kernel" \
    "${SDK}/usr/local/include/iBoot" \
    "${SDK}/System/Library/Frameworks/Kernel.framework/Versions/A/PrivateHeaders/AppleFeatures" \
    "${SDK}/System/Library/Frameworks/Kernel.framework/Versions/A/PrivateHeaders/platform" \
    "${SDK}/usr/local/include/kernel/firehose" \
    "${SDK}/usr/local/include/kernel/os" \
    "${SDK}/usr/local/include/kernel/CodeSignature" \
    "${SDK}/usr/local/include/kernel/DriverKit"

# availability.pl generates sys/_symbol_aliasing.h.
install -m 0755 "${CROSSXNU_AVAILABILITY}/availability.pl" "${SDK}/usr/local/libexec/availability.pl"
install -m 0755 "${CROSSXNU_AVAILABILITY}/availability" "${SDK}/usr/local/libexec/availability"
install -m 0644 "${CROSSXNU_AVAILABILITY}/availability.dsl" "${SDK}/usr/local/libexec/availability.dsl"

# Mach-O headers used by host tools and MIG.
cp -a "${XNU}/EXTERNAL_HEADERS/mach-o/." "${SDK}/usr/include/mach-o/"

# DriverKit: plain headers from XNU, generated ones as stubs until IIG is
# available.  The kernel build uses the non-generated subset.
cp -a "${XNU}/iokit/DriverKit/"*.h "${SDK}/usr/local/include/kernel/DriverKit/" 2>/dev/null || true
for h in OSObject IOService OSAction IOUserClient IOUserServer IOEventLink \
         IOWorkGroup IODispatchQueue IODispatchSource IOMemoryDescriptor \
         IOMemoryMap IOBufferMemoryDescriptor IODMACommand \
         IODataQueueDispatchSource IOInterruptDispatchSource \
         IOServiceNotificationDispatchSource \
         IOServiceStateNotificationDispatchSource IOExtensiblePaniclog; do
    if [[ ! -f "${SDK}/usr/local/include/kernel/DriverKit/${h}.h" ]]; then
        if [[ "${h}" == "IOUserServer" ]]; then
            printf '#pragma once\n/* generated by IIG on macOS; crossxnu stub */\nclass OSAction;\n' \
                > "${SDK}/usr/local/include/kernel/DriverKit/${h}.h"
        else
            printf '#pragma once\n/* generated by IIG on macOS; crossxnu stub */\n' \
                > "${SDK}/usr/local/include/kernel/DriverKit/${h}.h"
        fi
    fi
done

# Firehose and libdispatch's os/ headers.
cp -a "${XNU}/libkern/firehose/"*.h "${SDK}/usr/local/include/kernel/firehose/"
if [[ -d "${CROSSXNU_LIBDISPATCH}/os" ]]; then
    cp -a "${CROSSXNU_LIBDISPATCH}/os/"*.h "${SDK}/usr/local/include/kernel/os/"
fi

# XNU expects <CodeSignature/Entitlements.h>; the open-source tree ships
# the CoreEntitlements API under a different prefix.
cat > "${SDK}/usr/local/include/kernel/CodeSignature/Entitlements.h" <<'EOF'
#pragma once
#include <CoreEntitlements/CoreEntitlements.h>
EOF

echo "synthetic SDK: ${SDK}"
